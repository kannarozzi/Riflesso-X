/** Offered languages, each named in itself. Codes match `tray_labels` in main.rs. */
export const languages = [
  { code: "en", label: "English", messages: en },
  { code: "it", label: "Italiano", messages: it },
  { code: "es", label: "Español", messages: es },
  { code: "fr", label: "Français", messages: fr },
  { code: "de", label: "Deutsch", messages: de },
  { code: "pt-BR", label: "Português (Brasil)", messages: ptBR },
  { code: "ja", label: "日本語", messages: ja },
  { code: "zh-CN", label: "简体中文", messages: zhCN },
  { code: "ko", label: "한국어", messages: ko },
  { code: "ru", label: "Русский", messages: ru },
] as const;

export type Translate = (key: MessageKey, values?: Record<string, string | number>) => string;

function translator(language: string): Translate {
  const messages: Messages = languages.find((l) => l.code === language)?.messages ?? en;
  return (key, values) =>
    messages[key].replace(/\{(\w+)\}/g, (match, name: string) => (values && name in values ? String(values[name]) : match));
}

const I18n = createContext<Translate>(translator("en"));

export function I18nProvider({ language, children }: { language: string; children: ReactNode }) {
  return <I18n.Provider value={translator(language)}>{children}</I18n.Provider>;
}

export function useT(): Translate {
  return useContext(I18n);
}
